export function cropLabel(value, language) {
  if (language !== 'hi' || typeof value !== 'string') return value;
  const key = value.replaceAll(',', '').replace(/[_\s]+/g, ' ').trim().toLowerCase();
  return labelsHi[key] ?? value;
}
